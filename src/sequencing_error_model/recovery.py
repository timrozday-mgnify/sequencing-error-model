"""Recovery harness (plan §9 phase 3): generate reads from a known spec, run one evidence mode's source and
fitters on them, and compare the fitted spec with the truth.

A mode is a function (templates, reads, mates, truth) -> fitted spec; each evidence mode plugs one in as it
lands. `cigar_mode` refits from the generator's own CIGARs, the upper bound the other modes are judged by.

`compare` computes expectations under both specs on held-out generated tuples (not sampled counts, so the
curves carry no sampling noise), plus Q-track statistics from reads generated by each spec:

- errors: op-probability TV and KL, marginal rate, rate by read position and by reported Q;
- qualities: per-position Q histogram TV, Q lag-1 autocorrelation, empirical Q = -10 log10 P(error | Q).

`TOLERANCES` are the phase 2 exit criteria. `python -m sequencing_error_model.recovery` runs it at scale.
"""

